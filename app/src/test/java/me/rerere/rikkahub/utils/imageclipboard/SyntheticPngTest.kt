package me.rerere.rikkahub.utils.imageclipboard

import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import javax.imageio.ImageIO

/**
 * 校验合成 PNG 夹具本身: 结构合法、可解码、元数据完整、字节确定.
 *
 * 这些断言是剪贴板字节保真测试的前提 —— 如果夹具不再是合法 PNG, 或者不再确定,
 * 后面"暂存后字节不变"的断言就没有意义了.
 */
class SyntheticPngTest {
    @Test
    fun `chunk layout is a plain png without platform specific chunks`() {
        val chunks = SyntheticPng.chunks(SyntheticPng.bytes())

        assertEquals(listOf("IHDR", "tEXt", "iTXt", "IDAT", "IEND"), chunks.map { it.type })
        // chunks() 内部逐块校验 CRC, 走到这里说明长度和 CRC 都自洽
        assertEquals("IEND", chunks.last().type)
        assertTrue(chunks.last().data.isEmpty())
    }

    @Test
    fun `ihdr describes a small rgba8 image`() {
        val ihdr = SyntheticPng.chunks(SyntheticPng.bytes()).first { it.type == "IHDR" }.data

        assertEquals(13, ihdr.size)
        assertEquals(SyntheticPng.WIDTH, readIntBE(ihdr, 0))
        assertEquals(SyntheticPng.HEIGHT, readIntBE(ihdr, 4))
        assertEquals(8, ihdr[8].toInt() and 0xFF) // bit depth
        assertEquals(6, ihdr[9].toInt() and 0xFF) // color type RGBA
        assertEquals(0, ihdr[10].toInt() and 0xFF) // compression
        assertEquals(0, ihdr[11].toInt() and 0xFF) // filter
        assertEquals(0, ihdr[12].toInt() and 0xFF) // interlace
    }

    @Test
    fun `text chunks carry ascii and utf8 metadata`() {
        val chunks = SyntheticPng.chunks(SyntheticPng.bytes())

        assertEquals(
            SyntheticPng.SOFTWARE_TEXT,
            chunks.mapNotNull { SyntheticPng.textOf(it, SyntheticPng.SOFTWARE_KEYWORD) }.single(),
        )
        assertEquals(
            SyntheticPng.COMMENT_TEXT,
            chunks.mapNotNull { SyntheticPng.textOf(it, SyntheticPng.COMMENT_KEYWORD) }.single(),
        )
        // 非 ASCII 内容确实写进了 iTXt, 而不是被截断成 ASCII
        assertTrue(SyntheticPng.COMMENT_TEXT.any { it.code > 0x7F })
    }

    @Test
    fun `generated bytes match the published size and digest`() {
        val bytes = SyntheticPng.bytes()

        assertEquals(SyntheticPng.SIZE_BYTES, bytes.size)
        assertEquals(SyntheticPng.SHA256_HEX, SyntheticPng.sha256Hex(bytes))
        assertEquals(64, SyntheticPng.SHA256_HEX.length)
    }

    @Test
    fun `generator is deterministic and hands out independent arrays`() {
        val first = SyntheticPng.bytes()
        val second = SyntheticPng.bytes()

        assertArrayEquals(first, second)
        first.fill(0)
        assertEquals(SyntheticPng.SHA256_HEX, SyntheticPng.sha256Hex(SyntheticPng.bytes()))
    }

    @Test
    fun `image decodes to the expected pixels`() {
        val image = ImageIO.read(ByteArrayInputStream(SyntheticPng.bytes()))

        assertEquals(SyntheticPng.WIDTH, image.width)
        assertEquals(SyntheticPng.HEIGHT, image.height)
        for (y in 0 until SyntheticPng.HEIGHT) {
            for (x in 0 until SyntheticPng.WIDTH) {
                assertEquals(
                    "pixel ($x, $y)",
                    SyntheticPng.expectedArgb(x, y),
                    image.getRGB(x, y),
                )
            }
        }
    }

    /**
     * 反向对照: 只要实现把图片解码再重新编码, 元数据块就会消失, 字节也会变.
     * 剪贴板测试依赖这一点来证明"原样字节", 所以这里先证明对照条件成立.
     */
    @Test
    fun `decoding and re-encoding loses the text chunks and the original bytes`() {
        val original = SyntheticPng.bytes()
        val image = ImageIO.read(ByteArrayInputStream(original))

        val reEncoded = ByteArrayOutputStream().use { output ->
            ImageIO.write(image, "png", output)
            output.toByteArray()
        }

        val reEncodedChunks = SyntheticPng.chunks(reEncoded)
        assertFalse(reEncodedChunks.any { it.type == "tEXt" || it.type == "iTXt" })
        assertNotEquals(SyntheticPng.sha256Hex(original), SyntheticPng.sha256Hex(reEncoded))
    }

    private fun readIntBE(bytes: ByteArray, offset: Int): Int =
        ((bytes[offset].toInt() and 0xFF) shl 24) or
            ((bytes[offset + 1].toInt() and 0xFF) shl 16) or
            ((bytes[offset + 2].toInt() and 0xFF) shl 8) or
            (bytes[offset + 3].toInt() and 0xFF)
}
